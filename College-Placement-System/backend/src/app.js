import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import { env } from './config/env.js';
import sanitize from './middleware/sanitize.js';
import { notFound, errorHandler } from './middleware/error.js';
import authRoutes from './routes/auth.js';
import metaRoutes from './routes/meta.js';
import profileRoutes from './routes/profile.js';
import studentRoutes from './routes/students.js';
import companyRoutes from './routes/companies.js';
import driveRoutes from './routes/drives.js';
import applicationRoutes from './routes/applications.js';
import questionRoutes from './routes/questions.js';
import testRoutes from './routes/tests.js';
import attemptRoutes from './routes/attempts.js';
import practiceRoutes from './routes/practice.js';
import notificationRoutes from './routes/notifications.js';
import adminRoutes from './routes/admin.js';
import reportRoutes from './routes/reports.js';

const app = express();
app.disable('x-powered-by');
app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' } }));
app.use(cors({ origin: (origin, cb) => (!origin || env.origins.includes(origin) ? cb(null, true) : cb(new Error('Origin not allowed'))) }));
app.use(express.json({ limit: '1mb' }));
app.use(sanitize);

app.get('/', (_req, res) => res.send('Placement API is running. Open the website at http://localhost:5173 (API routes live under /api, e.g. /api/health).'));
app.get('/api/health', (_req, res) => res.json({ status: 'ok' }));
app.use('/api/auth', authRoutes);
app.use('/api/meta', metaRoutes);
app.use('/api/profile', profileRoutes);
app.use('/api/students', studentRoutes);
app.use('/api/companies', companyRoutes);
app.use('/api/drives', driveRoutes);
app.use('/api/applications', applicationRoutes);
app.use('/api/questions', questionRoutes);
app.use('/api/tests', testRoutes);
app.use('/api/attempts', attemptRoutes);
app.use('/api/practice', practiceRoutes);
app.use('/api/notifications', notificationRoutes);
app.use('/api/admin', adminRoutes);
app.use('/api/reports', reportRoutes);
app.use(notFound);
app.use(errorHandler);
export default app;
